def ws_api(params: dict) -> dict:
    global conn_cache
    path = "/w/api.php?" + urllib.parse.urlencode(params)
    for attempt in range(5):
        time.sleep(0.12)
        try:
            if conn_cache is None:
                conn_cache = http.client.HTTPSConnection("ru.wikisource.org", timeout=25, context=ssl_ctx)
            conn_cache.request("GET", path, headers=HEADERS)
            resp = conn_cache.getresponse()
            raw = resp.read()
            if resp.status == 429 or resp.status >= 500:
                conn_cache = None
                time.sleep(2.5 * (attempt + 1))
                continue
            if resp.getheader("Content-Encoding") == "gzip":
                raw = gzip.decompress(raw)
            return json.loads(raw.decode("utf-8"))
        except Exception:
            conn_cache = None
            time.sleep(1.0 * (attempt + 1))
    return {}


def slugify(text: str, max_len: int = 64) -> str:
    out = [TRANSLIT_MAP.get(ch, ch if ("a" <= ch <= "z" or "0" <= ch <= "9") else "-") for ch in text.lower().strip()]
    s = re.sub(r"-+", "-", "".join(out)).strip("-")
    return (s[:max_len].rstrip("-") if len(s) > max_len else s) or "school-book"


def clean_wikitext_to_blocks(wt: str) -> list:
    # Убираем шапку {{О тексте...}}
    m = re.search(r"\{\{\s*(?:Отексте|отексте|О\s+тексте)\b", wt)
    if m:
        st = m.start()
        depth = 0
        i = st
        n = len(wt)
        while i < n - 1:
            if wt[i : i + 2] == "{{":
                depth += 1
                i += 2
                continue
            if wt[i : i + 2] == "}}":
                depth -= 1
                i += 2
                if depth == 0:
                    wt = wt[:st] + "\n" + wt[i:]
                    break
                continue
            i += 1

    s = re.sub(r"<!--.*?-->", "", wt, flags=re.S)
    s = re.sub(r"\{\|.*?\|\}", "", s, flags=re.S)
    s = re.sub(r"\[\[\s*(?:Категория|Category|Файл|File|Изображение|Image)\s*:[^\]]+\]\]", "", s, flags=re.I)
    s = re.sub(r"<ref[^>]*/>", "", s, flags=re.I)
    s = re.sub(r"<ref[^>]*>.*?</ref>", "", s, flags=re.I | re.S)

    poems = []
    def keep_poem(mp):
        poems.append(mp.group(1))
        return f"\n\n@@POEM_{len(poems)-1}@@\n\n"
    s = re.sub(r"<poem[^>]*>(.*?)</poem>", keep_poem, s, flags=re.I | re.S)

    for _ in range(4):
        ns = re.sub(
            r"\{\{(?:Эпиграф|эпиграф|epigraph)\|([^{}]*?)\}\}",
            lambda me: " — ".join(p.strip() for p in me.group(1).split("|") if p.strip()),
            s,
            flags=re.S,
        )
        ns = re.sub(r"\{\{(?:right|center|left|блоки|цитата|Цитата|разрядка|sc)\|([^{}|]*?)(?:\|[^{}]*)?\}\}", r"\1", ns, flags=re.I | re.S)
        ns = re.sub(r"\{\{[^{}]*\}\}", "", ns, flags=re.S)
        if ns == s:
            break
        s = ns

    s = re.sub(r"\[\[(?:[^\]|]+\|)?([^\]]+)\]\]", r"\1", s)
    s = re.sub(r"\[https?://[^\s\]]+\s+([^\]]+)\]", r"\1", s)
    s = re.sub(r"\[https?://[^\]]+\]", "", s)
    s = re.sub(r"<br\s*/?>", "\n", s, flags=re.I)
    s = re.sub(r"<[^>]+>", "\n", s)
    s = html.unescape(s).replace("'''", "").replace("''", "")

    blocks = []
    for rb in re.split(r"\n\s*\n+", s):
        rb = rb.strip()
        if not rb:
            continue
        mp = re.fullmatch(r"@@POEM_(\d+)@@", rb)
        if mp:
            praw = html.unescape(re.sub(r"<[^>]+>", "", poems[int(mp.group(1))]))
            stanzas = [[vl.strip() for vl in ch.splitlines() if vl.strip()] for ch in re.split(r"\n\s*\n+", praw.strip())]
            stanzas = [st for st in stanzas if st]
            if stanzas:
                blocks.append({"type": "poem", "stanzas": stanzas, "text": "\n\n".join("\n".join(st) for st in stanzas)})
            continue
        mh = re.match(r"^(=+)\s*(.+?)\s*\1$", rb)
        if mh:
            ht = mh.group(2).strip()
            if ht and ht.lower() not in ("примечания", "сноски", "литература", "навигация"):
                blocks.append({"type": "h2", "text": ht})
            continue
        txt = re.sub(r"\s+", " ", rb).strip()
        if txt and not ("общественное достояние" in txt.lower() and len(txt) < 240):
            blocks.append({"type": "paragraph", "text": txt})
    return blocks


def blocks_to_chapters(blocks: list, fallback_title: str) -> list:
    h2_cnt = sum(1 for x in blocks if x["type"] == "h2")
    if h2_cnt >= 2:
        chapters = []
        ct, cc = "Вступление", []
        for x in blocks:
            if x["type"] == "h2":
                if cc:
                    chapters.append({"id": f"chapter-{len(chapters)+1}", "title": ct, "content": cc})
                    cc = []
                ct = x["text"][:140]
            else:
                cc.append(x)
        if cc:
            chapters.append({"id": f"chapter-{len(chapters)+1}", "title": ct, "content": cc})
        return chapters
    clean_c = [x for x in blocks if x["type"] != "h2"]
    if len(clean_c) > 80:
        return [
            {"id": f"chapter-{idx+1}", "title": f"Часть {idx+1}", "content": clean_c[i : i + 55]}
            for idx, i in enumerate(range(0, len(clean_c), 55))
        ]
    return [{"id": "chapter-1", "title": fallback_title, "content": clean_c}]


