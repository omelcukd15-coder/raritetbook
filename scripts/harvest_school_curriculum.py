def main():
    cat_data = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    books = cat_data["books"]
    seen_slugs = {b["slug"] for b in books}

    added_new = 0
    for prefix, clean_title, au_full, au_short, aslug, ayears, yr, cat_id, rnk in MISSING_SCHOOL_SPECS:
        # Проверяем, нет ли уже полного издания (не критики!) в базе
        already = [
            b for b in books
            if aslug == b.get("authorSlug")
            and clean_title.split("(")[0].strip().lower() == b.get("title", "").split("(")[0].strip().lower()
            and int(b.get("wordsCount", 0)) >= 250
        ]
        if already:
            already[0]["rank"] = max(int(already[0].get("rank", 0)), rnk)
            continue

        chs, src_url = fetch_full_wikisource_work(prefix, clean_title)
        if not chs:
            print(f"  [пропуск] не найдено: {prefix}", flush=True)
            continue

        words = sum(len(blk["text"].split()) for ch in chs for blk in ch["content"])
        chars = sum(len(blk["text"]) for ch in chs for blk in ch["content"])
        if words < 40:
            continue

        bslug = slugify(f"{aslug}-{clean_title}", 62)
        if bslug in seen_slugs:
            bslug = f"{bslug}-full"
        seen_slugs.add(bslug)

        rmin = max(2, round(words / 180))
        rel = f"/archive/books/{aslug}/{bslug}"
        first_p = chs[0]["content"][0]["text"][:170].replace("\n", " / ")
        desc = f"Классическое издание школьной программы ({au_short}, {yr}): {first_p}"

        payload = {
            "id": bslug,
            "slug": bslug,
            "shard": 1,
            "title": clean_title,
            "altTitles": [],
            "author": au_full,
            "authorShort": au_short,
            "authorSlug": aslug,
            "authorYears": ayears,
            "translator": None,
            "language": "ru",
            "category": cat_id,
            "writtenYear": yr,
            "editionYear": yr,
            "description": desc,
            "historicalNote": f"Проверенное полное издание школьной программы ({au_full}, {yr}).",
            "sourceUrl": src_url,
            "legalStatus": f"Общественное достояние (ст. 1281 ГК РФ; {au_short}, {ayears})",
            "downloadAllowed": True,
            "fb2Url": f"{rel}/original.fb2",
            "coverUrl": f"{rel}/cover.webp",
            "stats": {
                "chaptersCount": len(chs),
                "wordsCount": words,
                "charsCount": chars,
                "readingMinutes": rmin,
            },
            "toc": [{"id": c["id"], "title": c["title"]} for c in chs],
            "chapters": chs,
        }

        json_str = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        for root_dir in (BOOKS_DIR, SHARD1_BOOKS_DIR):
            bdir = root_dir / aslug / bslug
            bdir.mkdir(parents=True, exist_ok=True)
            (bdir / "book.json").write_text(json_str, encoding="utf-8")

        books.append({
            "id": bslug,
            "slug": bslug,
            "shard": 1,
            "rank": rnk,
            "title": clean_title,
            "altTitles": [],
            "author": au_full,
            "authorShort": au_short,
            "authorSlug": aslug,
            "authorYears": ayears,
            "translator": None,
            "language": "ru",
            "category": cat_id,
            "writtenYear": yr,
            "editionYear": yr,
            "description": desc[:90],
            "historicalNote": payload["historicalNote"][:120],
            "legalStatus": payload["legalStatus"],
            "sourceUrl": src_url,
            "downloadAllowed": True,
            "bookUrl": f"{rel}/book.json",
            "fb2Url": f"{rel}/original.fb2",
            "coverUrl": f"{rel}/cover.webp",
            "chaptersCount": len(chs),
            "wordsCount": words,
            "charsCount": chars,
            "readingMinutes": rmin,
        })
        added_new += 1
        print(f"  + [{added_new}] Добавлен шедевр программы: {au_short} — «{clean_title}» ({len(chs)} гл., {words:,} слов)", flush=True)

    build_sharded_indexes(books)
    build_school_curriculum_json(books)
    print(f"Добавлено новых полных книг программы: +{added_new}, всего книг в архиве: {len(books)}", flush=True)


if __name__ == "__main__":
    main()
