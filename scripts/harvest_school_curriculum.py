def fetch_full_wikisource_work(prefix: str, clean_title: str):
    # 1. Ищем страницы по точному префиксу без поискового движка (никаких 429!)
    ap = ws_api({"action": "query", "list": "allpages", "apprefix": prefix, "apnamespace": 0, "aplimit": 80, "format": "json"})
    pages = [p["title"] for p in ap.get("query", {}).get("allpages", []) if "/ДО" not in p["title"] and "(ДО)" not in p["title"]]
    if not pages:
        # Попробуем без автора в скобках
        short_pref = prefix.split("(")[0].strip()
        ap2 = ws_api({"action": "query", "list": "allpages", "apprefix": short_pref, "apnamespace": 0, "aplimit": 80, "format": "json"})
        pages = [p["title"] for p in ap2.get("query", {}).get("allpages", []) if "/ДО" not in p["title"] and "(ДО)" not in p["title"]]
    if not pages:
        return None, None

    # Проверяем, есть ли сводная одностраничная редакция (СО) или единственная страница
    so_candidates = [t for t in pages if "(СО)" in t or t == prefix]
    # Запрашиваем размеры кандидатов
    info_data = ws_api({"action": "query", "titles": "|".join(pages[:45]), "prop": "revisions", "rvslots": "main", "rvprop": "size|content", "format": "json"})
    page_map = {}
    for pg in info_data.get("query", {}).get("pages", {}).values():
        t = pg.get("title", "")
        rev = (pg.get("revisions") or [{}])[0]
        wt = rev.get("slots", {}).get("main", {}).get("*", "")
        page_map[t] = wt

    # а) Если есть крупная одностраничная версия (> 2500 символов текста без подстраниц)
    best_single = None
    for cand in ([t for t in pages if "(СО)" in t] + ([prefix] if prefix in page_map else []) + pages):
        wt = page_map.get(cand, "")
        if not wt:
            continue
        # Если это страница-оглавление со ссылками на подстраницы (/Глава, /Часть, /Действие) и мало текста — не берём как single
        sub_links = re.findall(r"\[\[(" + re.escape(cand) + r"/[^\]|]+)", wt)
        blocks = clean_wikitext_to_blocks(wt)
        words = sum(len(b["text"].split()) for b in blocks)
        if words >= 120 and len(sub_links) < 2:
            if best_single is None or words > best_single[1]:
                best_single = (cand, words, blocks)
        elif words >= 2500:
            best_single = (cand, words, blocks)
            break

    if best_single:
        cand_title, words, blocks = best_single
        chs = blocks_to_chapters(blocks, clean_title)
        src = f"https://ru.wikisource.org/wiki/{urllib.parse.quote(cand_title.replace(' ', '_'))}"
        return chs, src

    # б) Собираем многоглавную книгу из подстраниц в порядке ссылок оглавления корневой страницы!
    root = prefix if prefix in page_map else pages[0]
    root_wt = page_map.get(root, "")
    ordered_subs = []
    for m in re.finditer(r"\[\[([^\]|#]+)(?:\|([^\]]+))?\]\]", root_wt):
        target = m.group(1).strip()
        if target.startswith("/"):
            target = root + target
        if target.startswith(root + "/") and "/ДО" not in target and target not in ordered_subs:
            ordered_subs.append(target)

    if not ordered_subs:
        ordered_subs = [t for t in pages if t.startswith(root + "/") and "/ДО" not in t]

    if not ordered_subs:
        return None, None

    # Докачиваем недостающие подстраницы пачками по 20
    missing_subs = [t for t in ordered_subs if t not in page_map]
    for off in range(0, len(missing_subs), 20):
        batch = missing_subs[off : off + 20]
        d = ws_api({"action": "query", "titles": "|".join(batch), "prop": "revisions", "rvslots": "main", "rvprop": "content", "format": "json"})
        for pg in d.get("query", {}).get("pages", {}).values():
            t = pg.get("title", "")
            wt = (pg.get("revisions") or [{}])[0].get("slots", {}).get("main", {}).get("*", "")
            if wt:
                page_map[t] = wt

    chapters = []
    for sub_t in ordered_subs[:60]:
        wt = page_map.get(sub_t, "")
        if not wt:
            continue
        blocks = clean_wikitext_to_blocks(wt)
        clean_b = [b for b in blocks if b["type"] != "h2"]
        if sum(len(b["text"].split()) for b in clean_b) < 30:
            continue
        ch_name = sub_t.split("/", 1)[1].replace("_", " ").strip()
        chapters.append({"id": f"chapter-{len(chapters)+1}", "title": ch_name, "content": clean_b})

    if not chapters:
        return None, None

    src = f"https://ru.wikisource.org/wiki/{urllib.parse.quote(root.replace(' ', '_'))}"
    return chapters, src


